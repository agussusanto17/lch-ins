    "updated_at" = CURRENT_TIMESTAMP
FROM (VALUES
  ('2937', '29371'),
  ('205', '2058'),
  ('23001', '230011'),
  ('29313', '29313A')
) AS v("old_code", "new_code")
WHERE o."code" = v."old_code"
  AND NOT EXISTS (SELECT 1 FROM "occupations" x WHERE x."code" = v."new_code");

-- 2. Kode dan keterangan mengikuti Lampiran I. Kode yang belum ada ditambah.
INSERT INTO "occupations" ("code", "name", "is_active", "updated_at")
SELECT "code", "name", true, CURRENT_TIMESTAMP FROM "_ojk_occupation"
ON CONFLICT ("code") DO UPDATE
SET "name" = EXCLUDED."name",
    "is_active" = true,
    "updated_at" = CURRENT_TIMESTAMP;

-- Kode yang tidak ada di Lampiran I dinonaktifkan, tidak dihapus, karena bisa
-- sudah dipakai SPPA atau slip.
UPDATE "occupations" AS o
SET "is_active" = false,
    "updated_at" = CURRENT_TIMESTAMP
WHERE o."is_active"
  AND NOT EXISTS (SELECT 1 FROM "_ojk_occupation" x WHERE x."code" = o."code");

-- 3. Tarif per kelas konstruksi mengikuti Lampiran I.
INSERT INTO "tariff_occupation" ("occupation_id", "construction_class", "rate_min", "rate_max", "is_active", "updated_at")
SELECT o."id", t."cls", t."rate_min", t."rate_max", true, CURRENT_TIMESTAMP
FROM "_ojk_tariff" t
JOIN "occupations" o ON o."code" = t."code"
ON CONFLICT ("occupation_id", "construction_class") DO UPDATE
SET "rate_min" = EXCLUDED."rate_min",
    "rate_max" = EXCLUDED."rate_max",
    "is_active" = true,
    "updated_at" = CURRENT_TIMESTAMP;

