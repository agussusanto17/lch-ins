export interface EqZoneEntry {
  province: string
  regency: string
  zone: number
}

/** Cari zona gempa dari teks lokasi risiko, dicocokkan ke nama kabupaten atau kota. */
export function matchEqZone(location: string): EqZoneEntry | null {
  const q = location.toLowerCase()
  if (q.trim().length < 4) return null
  const hit = EQ_ZONES.find((z) =>
    q.includes(z.regency.toLowerCase().replace(/^(kab\.|kota)\s*/, ""))
  )
  return hit ?? null
}

const FLOOD_REGION_PROVINCES = ["Dki Jakarta", "Banten", "Jawa Barat"]

/** Wilayah tarif banjir mengikuti provinsi lokasi risiko. */
export function matchFloodRegion(location: string): string | null {
  const hit = matchEqZone(location)
  if (!hit) return null
  return FLOOD_REGION_PROVINCES.includes(hit.province)
    ? "Jakarta, Banten, Jawa Barat"
    : "Luar Jakarta, Banten, Jawa Barat"
}
